def disposition_check(records, disposition):
    """The published partition, re-derived from the record fields by plain predicate rather than by rule order.

    First-match-wins equals plain predicate application only when the rule predicates are pairwise disjoint, so
    this check is simultaneously a reproduction of every row and a proof that no match could be claimed twice.
    """
    published = {row["disposition"]: row["audit_ids"] for row in disposition["rows"]}
    by_rule = {name: sorted(r["audit_id"] for r in records if predicate(r))
               for name, predicate, _definition, _evidence, _reading in DISPOSITION_RULES}
    names = sorted(published)
    overlaps = sorted(f"{a} & {b}" for i, a in enumerate(names) for b in names[i + 1:]
                      if set(by_rule[a]) & set(by_rule[b]))
    rows = {name: {"matches_in_published_table": len(published[name]),
                   "matches_rederived_from_record_fields": len(by_rule[name]),
                   "audit_ids_identical": published[name] == by_rule[name]} for name in names}
    claimed_once = sorted(audit_id for ids in published.values() for audit_id in ids)
    confessional_names = [name for name, _p, _d, evidence, _r in DISPOSITION_RULES if evidence]
    return {
        "total_matches_partitioned": [disposition["total_matches_partitioned"], len(records)],
        "every_match_claimed_exactly_once": claimed_once == sorted(r["audit_id"] for r in records),
        "rule_predicates_are_pairwise_disjoint": not overlaps,
        "overlapping_rule_pairs": overlaps,
        "rows": rows,
        "all_rows_reproduced": all(row["audit_ids_identical"] for row in rows.values()),
        "dispositions_counted_as_evidence": confessional_names,
        "confessional_split_is_exhaustive": (
            len(by_rule["confessional_in_a_work_not_marked_dependent"])
            + len(by_rule["confessional_in_a_work_marked_dependent"])
            == sum(1 for r in records if r["analyst_verdict"] == "genuine_exclusivist_confession")),
        "headline": disposition["headline"],
        "reading": "the disposition table is generated by rule order and this check re-derives it by predicate, "
                   f"over the same {len(records)} records in the same run, so a row that double-counted or "
                   "dropped a match would read false here rather than ship quietly. Neither view reads the "
                   "shipped JSON, so this covers the artifact and any re-run of it",
    }


def apply_dependence(records, declared, derived):
    audit_work_set = {record["work_id"] for record in records}
    for record in records:
        work_id = record["work_id"]
        record["dependent_reprint_of"] = None
        record["counts_as_independent_attestation"] = True
        record["dependence_scope"] = None
        record["source_dependence_basis"] = ("no configured pair rule places this work's text in dependence on "
                                             "another corpus work")
        record["declared_pair_rules"] = declared.get(work_id, [])
        record["verbatim_overlap_with_declared_source"] = None
        for rule in derived.get(work_id, []):
            source = rule["source"]
            if source not in audit_work_set or not rule["exclude_from_independent_analysis"]:
                continue
            if record["original_textual_source"] is None:
                continue
            overlap = source_clause_present(source, record["sentence"])
            record["dependent_reprint_of"] = source
            record["counts_as_independent_attestation"] = False
            record["verbatim_overlap_with_declared_source"] = overlap
            record["dependence_scope"] = ("match_level" if record["anthology_voice"] == "reprinted translation"
                                          else "work_level")
            record["source_dependence_basis"] = (
                f"declared pair rule `{rule['relationship']}` with {source} "
                f"(exclude_from_independent_analysis={rule['exclude_from_independent_analysis']}): "
                f"{rule['rationale']}. This match resolves to {record['original_textual_source']}, and the "
                f"match's own sentence recurs verbatim in {source}: {overlap}. Scope of the marking: "
                + ("this match sits in the reprinted translation itself"
                   if record["dependence_scope"] == "match_level" else
                   "the work carries the non-independence rule as a whole; this match is not a line of the "
                   "reprinted translation, so it is marked on the work-level rule rather than on a reprint of "
                   "the source's own wording"))
            break


RAW_CACHE = {}


def source_clause_present(source_work_id, clause):
    """Is this exact wording printed in the declared source work too? Collapsed text, substring test."""
    if not clause:
        return None
    if source_work_id not in RAW_CACHE:
        RAW_CACHE[source_work_id] = collapse(read_raw(source_work_id))[0]
    return clause[:200].lower() in RAW_CACHE[source_work_id].lower()


def canonical_locator(record):
    work_id = record["work_id"]
    if work_id == "kjv_bible":
        if not record["internal_part"]:
            return None
        reference = (f"{record['internal_part']} {record['internal_chapter']}:{record['internal_verse']}"
                     if record["internal_verse"] else f"{record['internal_part']} {record['internal_chapter']}")
        return f"KJV {reference}"
    if work_id == "book_of_mormon":
        if not record["internal_part"]:
            return None
        head = record["internal_part"]
        return (f"Book of Mormon {head} {record['internal_chapter']}:{record['internal_verse']}"
                if record["internal_verse"] else f"Book of Mormon {head} {record['internal_chapter']}")
    if work_id == "quran_sale":
        if not record["internal_part"]:
            return None
        suffix = " [in translator's notes]" if record.get("in_translator_notes") else ""
        return f"Qur'an ({record['internal_part']}, Rodwell){suffix}, no verse numbers printed"
    if work_id == "sacred_books_east":
        if not record["anthology_section"]:
            return None
        if record["internal_chapter"]:
            return (f"Sacred Books of the East, {title_case(record['anthology_section'])}, sura "
                    f"{record['internal_chapter']} "
                    f"({record['attributed_in_text_to'] or 'unattributed'} translation, reprint)")
        return (f"Sacred Books of the East, {title_case(record['anthology_section'])} / "
                f"{title_case(record['anthology_subsection'])} "
                f"({record['attributed_in_text_to'] or 'editor'})")
    return record["passage_id"]


def per_work_counts(records, meta):
    works = sorted({record["work_id"] for record in records})
    table = []
    for work_id in works:
        subset = [r for r in records if r["work_id"] == work_id]
        as_is = sum(1 for r in subset if r["matched_in_as_is_scan"])
        normalised = len(subset)
        body = meta[work_id]
        raw = read_raw(work_id)[body["body_char_start"]:body["body_char_end"]]
        table.append({
            "work_id": work_id,
            "as_is_matches": as_is,
            "whitespace_normalised_matches": normalised,
            "delta_from_whitespace_normalisation": normalised - as_is,
            "passages_with_matches": len({r["passage_id"] for r in subset}),
            "whole_work_body_control_as_is": len(divinity_terms.COMPILED[FAMILY].findall(raw)),
            "whole_work_body_control_whitespace_normalised": len(
                divinity_terms.COMPILED[FAMILY].findall(re.sub(r"\s+", " ", raw))),
        })
    total_as_is = sum(row["as_is_matches"] for row in table)
    total_normalised = sum(row["whitespace_normalised_matches"] for row in table)
    return {
        "per_work": table,
        "totals": {"as_is_matches": total_as_is, "whitespace_normalised_matches": total_normalised,
                   "delta_from_whitespace_normalisation": total_normalised - total_as_is,
                   "works_matched": len(table)},
        "newly_caught_by_whitespace_normalisation": [
            {"work_id": r["work_id"], "passage_id": r["passage_id"], "canonical_locator": r["canonical_locator"],
             "matched_term": r["matched_term"], "original_textual_source": r["original_textual_source"],
             "analyst_verdict": r["analyst_verdict"], "sentence": r["sentence"]}
            for r in sorted(records, key=lambda r: (r["work_id"], r["match_raw_char_start"]))
            if r["new_in_whitespace_normalised_scan"]],
        "explanation": "Gutenberg's hard line-wraps break multiword literals, so `beside me there is no\\nGod` is "
                       "invisible to the instrument; the same patterns over whitespace-collapsed text are the "
                       "recall control. `whole_work_body_control` re-runs both scans over the whole raw body of "
                       "the work, which shows how much of the difference is the wrapper and how much is the "
                       "passage filter",
    }


# A mutually exclusive partition of every audited match, keyed on the verdict vocabulary plus the configured
