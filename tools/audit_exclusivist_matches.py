def missed_formula_probe(passages, family_compiled, work_body_start, locators):
    """Formula classes the family does not carry, over the whitespace-normalised eligible text of all 65 works.

    One alternation of all the probe patterns locates candidate positions in a single pass per passage, then the
    individual patterns attribute each candidate; attributing per pattern rather than from the alternation is
    what keeps a formula nested inside a longer one -- `none else beside` inside `I am, and none else beside me`
    -- from disappearing behind the longest form.
    """
    patterns = {name: re.compile(spec["pattern"], re.IGNORECASE)
                for name, spec in sorted(MISSED_FORMULAS.items())}
    candidates = re.compile("|".join(f"(?:{patterns[name].pattern})" for name in sorted(patterns)), re.IGNORECASE)
    hits = defaultdict(list)
    for passage in sorted(passage_set(passages), key=lambda p: p["passage_id"]):
        work_id = passage["work_id"]
        collapsed, mapping = collapse(passage["text"])
        family_spans = [(match.start(), match.end()) for match in family_compiled.finditer(collapsed)]
        for candidate in candidates.finditer(collapsed):
            for name, pattern in sorted(patterns.items()):
                for match in pattern.finditer(collapsed, candidate.start(),
                                              min(len(collapsed), candidate.end() + PROBE_WINDOW)):
                    if not candidate.start() <= match.start() < candidate.end():
                        continue
                    local = match.start()
                    printed_local = mapping[local]
                    body_start = passage["body_char_start"] + printed_local
                    raw_offset = work_body_start[work_id] + body_start
                    sentence = sentence_of(collapsed, local).strip()
                    claimant = bool(NON_DIVINE_CLAIMANT_FRAME.search(sentence))
                    covered = any(start <= local <= end for start, end in family_spans)
                    locator = locators[work_id].locate(raw_offset) if work_id in locators else {}
                    hits[name].append({
                        "formula": name,
                        "work_id": work_id,
                        "passage_id": passage["passage_id"],
                        "section_index": passage["section_index"],
                        "section_heading": passage["section_heading"],
                        "body_char_start": body_start,
                        "match_raw_char_start": raw_offset,
                        "matched_term": match.group(0),
                        "covered_by_current_pattern_set": covered,
                        "anthology_section": locator.get("anthology_section"),
                        "anthology_voice": locator.get("anthology_voice"),
                        "internal_part": locator.get("part"),
                        "internal_chapter": locator.get("chapter") or locator.get("sura"),
                        "internal_verse": locator.get("verse"),
                        "locator": locator_label(locator, passage),
                        "speaker_frame": "divine_formula_in_non_divine_mouth" if claimant
                                         else "divine_or_narrative_assertion",
                        "sentence": sentence[:240],
                        "adjudication_provenance": ADJUDICATION_PROVENANCE,
                    })
    formulas = {}
    for name, spec in sorted(MISSED_FORMULAS.items()):
        subset = sorted(hits[name], key=lambda r: (r["work_id"], r["match_raw_char_start"]))
        formulas[name] = {
            "pattern": spec["pattern"],
            "why_the_family_misses_it": spec["note"],
            "literal_form_only": bool(spec.get("literal_only")),
            "occurrences": len(subset),
            "works": sorted({r["work_id"] for r in subset}),
            "work_counts": {work: count for work, count in
                            sorted(Counter(r["work_id"] for r in subset).items())},
            "uncovered_by_current_pattern_set": sum(1 for r in subset if not r["covered_by_current_pattern_set"]),
            "hits": subset,
        }
    non_divine = [record for name in sorted(formulas) for record in formulas[name]["hits"]
                  if record["speaker_frame"] == "divine_formula_in_non_divine_mouth"]
    return {
        "purpose": "formula classes that occur in these texts and are absent from the family's pattern list, so "
                   "the recall gap is measurable; they are deliberately not folded into the family, because "
                   "widening the regex without this audit's match-level adjudication reproduces the error that "
                   "made the published count untrustworthy",
        "corpus_scanned": "whitespace-normalised eligible passages of every work in the passage index",
        "formulas": formulas,
        "totals": {"formula_classes": len(formulas),
                   "occurrences": sum(item["occurrences"] for item in formulas.values()),
                   "uncovered_occurrences": sum(item["uncovered_by_current_pattern_set"]
                                                 for item in formulas.values())},
        "divine_formula_in_non_divine_mouth": {
            "verdict": "divine_formula_in_non_divine_mouth",
            "note": "the divine first-person confession form spoken by a claimant the text does not endorse. "
                    "These are the cases a widened regex would count as confessions, and they matter more than "
                    "the recall fix: the identical wording carries opposite doctrinal force depending on who is "
                    "printed as saying it",
            "cases": sorted(non_divine, key=lambda r: (r["work_id"], r["match_raw_char_start"])),
            "occurrences": len(non_divine),
            "distinct_verses": len({(record["work_id"], record["locator"]) for record in non_divine}),
            "counting_note": "a verse carrying the confession form twice -- once as a whole formula and once as a "
                             "shorter formula nested inside it -- is one `case` per formula class, because each "
                             "class is a separate pattern a widened census would carry; `distinct_verses` is the "
                             "number of places in the text",
            "adjudication_provenance": ADJUDICATION_PROVENANCE,
        },
    }


def passage_set(passages):
    return [p for p in passages if p["eligible_for_similarity"]]


def locator_label(locator, passage):
    chapter = locator.get("chapter") or locator.get("sura")
    if locator.get("part") and chapter is not None:
        verse = f":{locator['verse']}" if locator.get("verse") else ""
        return f"{locator['part']} {chapter}{verse}"
    if locator.get("anthology_section"):
        return f"{locator['anthology_section']} / {locator.get('anthology_subsection')}"
    return (f"passage section {passage['section_index']}: "
            f"`{(passage['section_heading'] or '')[:60]}` (no printed-matter locator for this work)")


