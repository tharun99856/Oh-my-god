SMALL_COUNT_WORDS = {0: "no", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
                     8: "eight", 9: "nine", 10: "ten"}


def independence_statement(confessional):
    """The sentence the independence column may say, assembled from the partition's own counts."""
    works = SMALL_COUNT_WORDS.get(len(confessional["works"]), str(len(confessional["works"])))
    return (f"{confessional['matches']} matches classified as confessional across {works} works not marked "
            f"dependent under the currently configured source-dependence rules. Independence has not been "
            f"established because dependence closure remains incomplete.")


def disposition_table(records):
    claimed, rows = {}, []
    for name, predicate, definition, evidence, reading in DISPOSITION_RULES:
        subset = [r for r in records if r["audit_id"] not in claimed and predicate(r)]
        for record in subset:
            claimed[record["audit_id"]] = name
        rows.append({
            "disposition": name,
            "definition": definition,
            "matches": len(subset),
            "works": {work_id: count for work_id, count in
                      sorted(Counter(r["work_id"] for r in subset).items())},
            "verdicts_inside_the_disposition": {
                verdict: count for verdict, count in
                sorted(Counter(r["analyst_verdict"] for r in subset).items())},
            "audit_ids": sorted(r["audit_id"] for r in subset),
            "counts_as_evidence_for_the_family": evidence,
            "what_it_evidences": reading,
        })
    unclaimed = sorted(r["audit_id"] for r in records if r["audit_id"] not in claimed)
    if unclaimed:
        raise SystemExit(f"disposition table does not cover {len(unclaimed)} match(s): {unclaimed[:5]}")
    total = len(records)
    summed = sum(row["matches"] for row in rows)
    if summed != total or len(set(claimed)) != total:
        raise SystemExit(f"disposition rows sum to {summed} over {total} records with {len(set(claimed))} claimed")
    confessional = next(row for row in rows if row["disposition"] == "confessional_in_a_work_not_marked_dependent")
    dependent = next(row for row in rows if row["disposition"] == "confessional_in_a_work_marked_dependent")
    return {
        "total_matches_partitioned": total,
        "sum_of_disposition_rows": summed,
        "sum_equals_total": summed == total,
        "dispositions_with_zero_matches": [row["disposition"] for row in rows if not row["matches"]],
        "mutually_exclusive_by_construction": "rules are evaluated in order and the first match claims the record, "
                                             "and a record no rule claims stops the run",
        "rows": rows,
        "dispositions_counted_as_evidence_for_the_family": [row["disposition"] for row in rows
                                                            if row["counts_as_evidence_for_the_family"]],
        "confessional_matches_total": confessional["matches"] + dependent["matches"],
        "headline": independence_statement(confessional),
        "reading": "the published family count is a regular-expression count; this table is the same match set "
                   "after attribution and adjudication, cut once so the rows cannot overlap and sum to the total. "
                   f"Of {total} matches, {confessional['matches'] + dependent['matches']} are confessional, and "
                   f"{dependent['matches']} of those sit in works the configured rules mark dependent. The "
                   f"{confessional['matches']} remaining are the largest set any independence sentence may be "
                   "about, and even they are described as confessional-in-not-marked-dependent rather than as "
                   "independent attestations, because the rules that mark a work dependent are a declared list, "
                   "not a closure: an undeclared dependence would move a match into this row while leaving it "
                   "non-independent in fact",
    }


