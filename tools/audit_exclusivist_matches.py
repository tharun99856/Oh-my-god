class QuranRodwellIndex:
    """Sura from the printed `SURA <roman>. Title [<roman>.]` headings; the bracketed roman is this edition's
    own order.

    The edition prints no verse numbers -- its inline digits are footnote references (they sit mid-clause, e.g.
    `And some4 there are`), so a verse-level locator would have to be invented and is published as null.
    """

    work_id = "quran_sale"

    def __init__(self, text, body_start):
        self.text = text
        self.suras = []
        for match in re.finditer(r"(?m)^SURA[^\r\n]{0,90}(?=\r\n)", text):
            line = match.group(0)
            rest = line[4:].lstrip("0123456789. -")
            roman = re.match(r"[IVXLCDM]+", rest)
            if not roman:
                continue
            tail = rest[roman.end():]
            bracket = re.search(r"\[\s*(?:\d+\.?\s*)?([IVXLCDM]+)\.?\s*\]", tail)
            title = tail[:tail.find("[")] if "[" in tail else tail
            title = re.sub(r"\s+", " ", re.sub(r"\d+", "", title)).strip(" .,-")
            self.suras.append({"offset": match.start(), "sura": roman_to_int(roman.group(0)),
                               "edition_order": roman_to_int(bracket.group(1)) if bracket else None,
                               "title": title, "heading": line})
        self.suras.sort(key=lambda item: item["offset"])
        self.offsets = [sura["offset"] for sura in self.suras]
        self.note_dividers = sorted(m.start() for m in re.finditer(r"_{6,}", text))
        self.title_page = re.sub(r"\s+", " ", text[body_start:body_start + 400])

    def locate(self, offset):
        index = bisect.bisect_right(self.offsets, offset) - 1
        if index < 0:
            return {"reason": "the match precedes the first printed sura heading, so it lies in the "
                              "introduction or the sura-number concordance at the head of this file"}
        sura = self.suras[index]
        next_heading = self.offsets[index + 1] if index + 1 < len(self.offsets) else len(self.text)
        dividers = [d for d in self.note_dividers if sura["offset"] < d < next_heading]
        in_notes = bool(dividers) and offset > dividers[0]
        return {"part": f"sura {sura['sura']} ({sura['title'].title()})", "sura": sura["sura"],
                "sura_title": sura["title"], "edition_order": sura["edition_order"],
                "printed_heading": sura["heading"], "tradition_layer": "Qur'an",
                "chapter": None, "verse": None, "in_translator_notes": in_notes, "language": "Arabic",
                "basis": f"the match offset lies under the printed heading `{sura['heading']}` in "
                         f"corpus/raw/quran_sale.txt; that file's own title page reads "
                         f"`{re.sub(chr(96), chr(39), self.title_page)[:150]}`, so the work_id `quran_sale` "
                         f"names a different translator than the text it labels",
                "reason": "the printed text supplies no verse numbers -- its inline digits are this edition's "
                          "footnote references -- so a verse locator would be invented"}


class AnthologyIndex:
    """Wilson's anthology, resolved from the volume's own CONTENTS page, all-caps body headings, bylines and
    signature initials.

    The section index is built from the file rather than from a per-passage table: the CONTENTS page lists the
    six parts in ALL CAPS and Sale's five reprinted chapters by title, the body repeats each part title as an
    all-caps heading, each translation is entered under a `Translation by ...` byline, the essays carry their
    own `By ...` byline, and each editorial introduction ends with the editor's initials `E.W.`.
    """

    work_id = "sacred_books_east"
    PARTS_OF_INTEREST = ("VEDIC HYMNS", "ZEND-AVESTA", "DHAMMAPADA", "UPANISHADS", "KORAN", "LIFE OF BUDDHA")

    def __init__(self, text, body_start):
        self.text = text
        contents = re.search(r"(?m)^CONTENTS(?=\r\n)", text)
        listed = [match.group(1).strip() for match in
                  re.finditer(r"(?m)^([A-Z][A-Z .\-&']{4,})(?=\r\n)", text[contents.end():])]
        first_part = listed[0]
        # the CONTENTS page necessarily lists the first part, and the body necessarily repeats it
        contents_entry = text.index(first_part, contents.end())
        body_start_of_parts = text.index(first_part, contents_entry + len(first_part))
        window = text[contents.end():body_start_of_parts]
        self.contents_titles = [match.group(1).strip() for match in
                                re.finditer(r"(?m)^([A-Z][A-Z .\-&']{4,})(?=\r\n)", window)]
        self.majors = []
        cursor = body_start_of_parts
        for title in dict.fromkeys(self.contents_titles):
            offset = find_part_heading(text, title, cursor)
            if offset is not None:
                self.majors.append({"offset": offset, "title": title})
                cursor = offset + 1
        self.offsets = [part["offset"] for part in self.majors]
        self.headings = [(m.start(), m.group(1).strip()) for m in
                         re.finditer(r"(?m)^([A-Z][A-Z .\-&']{4,})(?=\r\n)", text)
                         if m.start() >= body_start_of_parts]
        self.bylines = []
        for match in re.finditer(r"(?m)^(?:Translation by|Translated by|By) ([^\r\n]{3,45})(?=\r\n)", text):
            name = match.group(1).strip().rstrip(".")
            words = name.split()
            # rejects unrelated prose such as the contents sub-line "By Spiritual Power Fixing His Term of Years"
            if len(words) > 5 or not all(re.match(r"[A-Z]\.?[A-Za-z\-]*\.?$", word) for word in words):
                continue
            self.bylines.append({"offset": match.start(), "name": name})
        self.signatures = sorted(m.start() for m in re.finditer(r"(?m)^E\.W\.(?=\r\n)", text))
        self.sura_titles = {}
        for match in re.finditer(r"(?m)^Chapter ([IVXLCDM]+)[.\- ]{2,}Entitled,? ([^\r\n]+?)(?=\r\n)", window):
            self.sura_titles[roman_to_int(match.group(1))] = match.group(2).strip()
        self.chapters = sorted((m.start(), roman_to_int(m.group(1))) for m in
                               re.finditer(r"(?m)^CHAPTER ([IVXLCDM]+)(?=\r\n)", text))
        self.chapter_offsets = [chapter[0] for chapter in self.chapters]

    def _byline_for(self, offset):
        """A byline governs only until the next all-caps heading, so an essay byline cannot leak to the
        translation that follows it; failing a governing byline, fall back to the part's own byline."""
        for position, entry in enumerate(self.bylines):
            if entry["offset"] > offset:
                break
            next_heading = next((h for h, _ in self.headings if h > entry["offset"]), len(self.text))
            if entry["offset"] < offset < next_heading:
                return entry["name"], "subsection byline"
        index = bisect.bisect_right(self.offsets, offset) - 1
        if index >= 0:
            part_offset = self.majors[index]["offset"]
            for entry in self.bylines:
                if part_offset <= entry["offset"] < part_offset + 400:
                    return entry["name"], "part byline"
        return None, "no byline printed in scope"

    def locate(self, offset):
        index = bisect.bisect_right(self.offsets, offset) - 1
        section = self.majors[index]["title"] if index >= 0 else None
        sub_index = bisect.bisect_right([h for h, _ in self.headings], offset) - 1
        subsection = self.headings[sub_index][1] if sub_index >= 0 else None
        attributed, attribution_scope = self._byline_for(offset)
        sura = None
        if section and "KORAN" in section:
            c_index = bisect.bisect_right(self.chapter_offsets, offset) - 1
            if c_index >= 0 and (index + 1 >= len(self.majors) or
                                 self.chapters[c_index][0] >= self.majors[index]["offset"]):
                sura = self.chapters[c_index][1]
        # an editorial part is one whose heading is an essay or an introduction, i.e. not a printed chapter of
        # the reprinted translation and not carrying the part's own translation byline
        editorial = subsection in ("INTRODUCTION", "CONTENTS", "MOHAMMED AND MOHAMMEDANISM") or \
            (subsection is not None and sura is None and "CHAPTER" not in (subsection or ""))
        signed = bool(self.signatures) and any(entry < offset for entry in self.signatures)
        return {"part": section, "anthology_section": section, "anthology_subsection": subsection,
                "anthology_voice": "editorial commentary" if editorial else "reprinted translation",
                "attributed_in_text_to": attributed, "attribution_scope": attribution_scope,
                "editor_initials_present_before_match": signed,
                "sura": sura, "sura_title": self.sura_titles.get(sura), "chapter": sura, "verse": None,
                "language": language_of_section(section, editorial),
                "tradition_layer": "Qur'an via Wilson anthology" if section and "KORAN" in section
                                   else (section.title() if section else None),
                "basis": f"the match offset lies between the part heading `{section}` and the next part heading, "
                         f"under the subsection heading `{subsection}`; attribution follows the "
                         f"{attribution_scope}"
                         + (f" `{attributed}`" if attributed else ""),
                "reason": ("the match sits in the anthology's editorial matter, which reports doctrine and "
                           "quotes no scripture text of its own" if editorial
                           else "the match sits in a translation reprinted inside the anthology, not in an "
                                "independent witness")}


def find_part_heading(text, title, cursor):
    """The body heading for a CONTENTS title: exact line, or a line ending with that title."""
    positions = [m.start() for m in re.finditer(r"(?m)^([^\r\n]*" + re.escape(title) + r")(?=\r\n)", text)
                 if m.start() >= cursor and (m.group(1) == title or m.group(1).endswith(" " + title))]
    return positions[0] if positions else None


def language_of_section(section, editorial):
    table = {"VEDIC HYMNS": "Sanskrit", "THE ZEND-AVESTA": "Avestan", "THE DHAMMAPADA": "Pali",
             "THE UPANISHADS": "Sanskrit", "SELECTIONS FROM THE KORAN": "Arabic",
             "LIFE OF BUDDHA": "Sanskrit (Chinese translation by Samuel Beal)"}
    return table.get(section)


