class KingJamesIndex:
    """Book from the volume's own table of contents; chapter and verse from its inline `C:V` markers."""

    work_id = "kjv_bible"

    def __init__(self, text, body_start):
        self.text = text
        first_verse = text.index("1:1 In the beginning", body_start)
        contents_end = text.rfind("\r\nThe First Book of Moses: Called Genesis\r\n", body_start, first_verse)
        titles = [line for line in text[body_start:contents_end].split("\r\n") if line.strip()]
        self.books = []
        testament = titles[0]
        cursor = contents_end
        for title in titles:
            if "Testament" in title:
                testament = title
                continue
            offset = text.find("\r\n" + title + "\r\n", cursor)
            if offset == -1:
                continue
            self.books.append({"offset": offset, "title": title, "testament": testament})
            cursor = offset + 1
        self.offsets = [book["offset"] for book in self.books]

    def locate(self, offset):
        index = bisect.bisect_right(self.offsets, offset) - 1
        if index < 0:
            return {"reason": "the match falls in the volume's front matter, before any printed book heading"}
        book = self.books[index]
        markers = [m for m in VERSEC.finditer(self.text, book["offset"], offset + 1)]
        chapter, verse = (markers[-1].group(1), markers[-1].group(2)) if markers else (None, None)
        old_testament = "Old Testament" in book["testament"]
        return {"part": book["title"].split(": Called ")[-1],
                "printed_heading": book["title"],
                "testament": "Old Testament" if old_testament else "New Testament",
                "tradition_layer": "Hebrew Bible / Old Testament" if old_testament else "New Testament",
                "chapter": chapter, "verse": verse,
                "language": "Hebrew (Masoretic text)" if old_testament else "Greek (Koine)",
                "basis": f"the match offset lies between the printed book heading "
                         f"`{book['title']}` and the next book heading in corpus/raw/kjv_bible.txt, and the "
                         f"chapter and verse come from the nearest preceding `chapter:verse ` marker printed in "
                         f"the body of that book",
                "reason": None if verse else "no `chapter:verse` marker is printed between the book heading and "
                                             "the match"}


