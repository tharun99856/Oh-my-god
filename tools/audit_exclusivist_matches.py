"""Match-level audit of the `exclusivist_monotheism` grammar.

The census in `divinity_terms.py` publishes this family as 46 term hits in 4 works across 4 traditions, and
that distribution is read as showing that exclusivist monotheism is confined to the Abrahamic family. A family
count is a regular-expression count over English translation prose, so it can be wrong in three separate ways
at once: the work carrying the hits may not be an independent witness; a hit may not be a confession of
doctrine at all; and a real confession may be invisible because the passage text still contains Gutenberg's
hard line-wraps. This tool audits the family match by match and publishes all three corrections next to the
published figures.

The regex source of truth is imported from `divinity_terms` (`FAMILIES`/`COMPILED`), never copied, so this
audit cannot drift from the probe it audits. Nothing here modifies the probe.

Attribution is resolved from each work's own printed matter -- table of contents, book and chapter headings,
translator bylines, signature initials -- not from the analyst's outside knowledge of the texts. Where the
printed text cannot support a locator (neither Qur'an witness prints verse numbers) the field is published as
null with the reason, never filled in from outside.

Adjudication is one analyst reading the published context of each match. No second coder has reviewed any
verdict, so every record carries `adjudication_provenance` and the `limitations` block states what the verdict
column is and is not: it is the input to a reliability test, not its result.

Every audited match is also placed in exactly one disposition (`disposition_table`): the rows are a mutually
exclusive partition generated by rule order, so the table cannot both double-count a match and drop one, and a
match no rule claims stops the run. This is what lets the file state how many confessional matches sit in works
the configured rules do not mark dependent, without calling them independent attestations -- the rules are a
declared list, not a closure over sources, so independence remains unestablished.

Determinism: no randomness, no sampling, no thresholds, sorted iteration, stdlib only, no network.
"""

