VERSEC = re.compile(r"(?<![\d:])(\d{1,3}):(\d{1,3})(?= )")


def collapse(text):
    """Whitespace-collapsed copy of `text`, plus a map from collapsed index to original index.

    Gutenberg prints hard line-wraps, so a multiword pattern can straddle a newline and be invisible to the
    instrument. Collapsing finds those hits, and the map reports them back in the instrument's own coordinates.
    """
    out = []
    mapping = []
    position = 0
    for match in re.finditer(r"\s+", text):
        chars = text[position:match.start()]
        out.append(chars)
        mapping.extend(range(position, match.start()))
        if not (out and out[-1].endswith(" ")):
            out.append(" ")
            mapping.append(match.start())
        position = match.end()
    chars = text[position:]
    out.append(chars)
    mapping.extend(range(position, position + len(chars)))
    return "".join(out), mapping


