def original_source(work_id, locator):
    """The composition the matched words belong to, plus how that was decided from the printed text."""
    if not locator:
        return None, "no printed-matter locator exists for this work; attribution would come from outside " \
                     "knowledge and is therefore not published", "no locator for this work"
    if work_id == "sacred_books_east":
        section = locator.get("anthology_section")
        if not section:
            return None, "unresolved", "no anthology part heading precedes the match offset"
        if locator["anthology_voice"] == "editorial commentary":
            attributed, scope = locator["attributed_in_text_to"], locator["attribution_scope"]
            if scope == "subsection byline" and attributed:
                source = (f"editorial commentary in the anthology: the essay "
                          f"`{title_case(locator['anthology_subsection'])}`, printed in the volume under the "
                          f"byline `By {attributed}`, inside the `{title_case(section)}` part")
            else:
                source = (f"editorial commentary in the anthology: `{title_case(section)} / "
                          f"{title_case(locator['anthology_subsection'])}`, the volume's own editorial matter "
                          f"(its introductions end with the editor's initials `E.W.`, and the title page names "
                          f"Epiphanius Wilson as the editor of these sketches)")
            return (source,
                    f"resolved from the volume's heading sequence and bylines: {locator['basis']}",
                    locator["reason"])
        if "KORAN" in section and locator.get("sura"):
            title = locator.get("sura_title")
            source = (f"Qur'an, sura {locator['sura']}" + (f" ({title})" if title else "")
                      + f" -- {locator['attributed_in_text_to'] or 'the'} translation as reprinted inside "
                        f"Wilson's Sacred Books of the East")
            basis = (f"the anthology's CONTENTS page lists `Chapter {roman_from_int(locator['sura'])}.--"
                     f"Entitled, {title}` under `{section}`, the part is entered under the byline `Translation "
                     f"by {locator['attributed_in_text_to']}`, and the match offset lies under the body heading "
                     f"`{locator['anthology_subsection']}`; {locator['basis']}")
            return (source, basis, None)
        return (f"Sacred Books of the East, `{title_case(section)}` part"
                + (f", subsection `{title_case(locator['anthology_subsection'])}`"
                   if locator["anthology_subsection"] else ""),
                f"resolved from the volume's CONTENTS titles and all-caps body headings: {locator['basis']}",
                None)
    if not locator.get("part"):
        return None, "unresolved", locator.get("reason")
    if work_id == "kjv_bible":
        reference = f"{locator['part']} {locator['chapter']}:{locator['verse']}" if locator["verse"] \
            else f"{locator['part']} chapter {locator['chapter']}"
        return (f"{locator['tradition_layer']}, {reference} (King James Version)", locator["basis"],
                locator["reason"])
    if work_id == "book_of_mormon":
        reference = (f"{locator['printed_heading']}, verse {locator['verse']}" if locator["verse"]
                     else locator["printed_heading"])
        return (f"Book of Mormon narrative voice, {reference}", locator["basis"], locator["reason"])
    if work_id == "quran_sale":
        if locator.get("in_translator_notes"):
            return (f"the translator's notes to sura {locator['sura']} in this edition, not the Qur'an text",
                    f"the match offset lies after the `______` divider that opens the footnote block of this "
                    f"sura in corpus/raw/quran_sale.txt; {locator['basis']}", locator["reason"])
        return (f"Qur'an, sura {locator['sura']} ({locator['sura_title'].title()}), Rodwell's translation -- "
                f"which is what the work_id `quran_sale` actually holds",
                locator["basis"], locator["reason"])
    return None, "unresolved", "no locator rule for this work"


def title_case(heading):
    return heading.title() if heading else heading


