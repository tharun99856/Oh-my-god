def roman_to_int(roman):
    values = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}
    total = previous = 0
    for char in reversed(roman):
        value = values[char]
        total += value if value >= previous else -value
        previous = max(previous, value)
    return total


def roman_from_int(value):
    table = [(1000, "M"), (900, "CM"), (500, "D"), (400, "CD"), (100, "C"), (90, "XC"), (50, "L"), (40, "XL"),
             (10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I")]
    out = ""
    for divisor, numeral in table:
        while value >= divisor:
            out += numeral
            value -= divisor
    return out


def sentence_of(collapsed_text, position):
    """The sentence containing `position`, cut at the printed division marks."""
    start = max(collapsed_text.rfind(mark, 0, position) for mark in ".!?") + 1
    ends = [end for end in (collapsed_text.find(mark, position) for mark in ".!?") if end != -1]
    return collapsed_text[start:min(ends) + 1 if ends else len(collapsed_text)]


