def match_spans(passage, compiled, mode, work_body_start, collapsed, mapping):
    """Match offsets for one passage, returned in both the raw file's and the collapsed text's coordinates.

    The instrument's coordinate system is the raw file's, so hits found on the collapsed copy are translated
    back with `mapping`; the collapsed index travels with it because the context and the sentence are read out
    of the collapsed copy, where the printed line-wraps no longer break them apart.
    """
    text = passage["text"]
    base = work_body_start + passage["body_char_start"]
    spans = []
    if mode == "as_is":
        for match in compiled.finditer(text):
            local = bisect.bisect_left(mapping, match.start())
            spans.append((base + match.start(), base + match.end(), match.group(0),
                          text[match.start():match.end()], local))
        return spans
    for match in compiled.finditer(collapsed):
        local = match.start()
        start = mapping[local]
        end = mapping[match.end() - 1] + 1
        spans.append((base + start, base + end, match.group(0), text[start:end], local))
    return spans


def patterns_for(term, local_start, text, individual):
    """Which individual patterns of the family produce this term at this place -- never guessed from the
    alternation, because the alternation cannot tell a Shema from a substring collision."""
    hits = []
    for pattern, compiled in individual.items():
        for match in compiled.finditer(text, local_start, local_start + len(term) + LOOKAHEAD_CHARS):
            if match.start() == local_start and match.group(0) == term:
                hits.append(pattern)
                break
    return sorted(hits)


def rule_decides(rule, record):
    sentence = record["sentence"]
    if rule == "anthology_voice_is_editorial":
        return ("editorial_description_of_formula",
                f"the match lies in the anthology's editorial matter (`{record['anthology_subsection']}`, "
                f"{record['attributed_in_text_to'] or 'signed by the editor'}), which describes the formula "
                f"being recited rather than stating the doctrine: `{sentence[:200]}`")
    if rule == "match_lies_in_translator_notes":
        return ("editorial_description_of_formula",
                "the match lies in this edition's footnote apparatus rather than in the translated text: "
                f"`{sentence[:200]}`")
    if rule == "confession_form_in_a_non_divine_claimants_frame":
        return ("divine_formula_in_non_divine_mouth",
                f"the text reports the form as a claimant's private self-assertion, not as a confession: "
                f"`{sentence[:200]}`")
    if rule == "bare_lord_is_one_not_predicated_of_the_lord":
        return ("non_doctrinal_substring_collision",
                f"`{record['matched_term']}` is a substring collision: `{sentence[:200]}` predicates oneness of "
                f"something other than divinity, and the pattern `\\bthe lord is one\\b` reaches it only because "
                f"the following word is not `Lord`")
    if rule == "no_other_gods_regulates_worship_not_existence":
        return ("monolatrous_prohibition_presupposing_other_gods",
                f"`{sentence[:200]}` regulates worship, invocation or association, and grammatically "
                f"presupposes that other gods exist to be regulated: it denies their claim, not their being")
    if rule == "formula_inside_hypothetical_protasis":
        return ("conditional_or_hypothetical",
                f"the formula stands inside the hypothesis of `{sentence[:200]}`, so neither the confession nor "
                f"its denial is asserted")
    return None


CONTEXT_RULES = (
    ("anthology_voice_is_editorial", lambda r: r["work_id"] == "sacred_books_east"
     and r["anthology_voice"] == "editorial commentary"),
    ("match_lies_in_translator_notes", lambda r: bool(r.get("in_translator_notes"))),
    ("confession_form_in_a_non_divine_claimants_frame", lambda r: bool(NON_DIVINE_CLAIMANT_FRAME.search(
        r["sentence"]))),
    ("bare_lord_is_one_not_predicated_of_the_lord", lambda r: r["patterns_matched"] == [r"\bthe lord is one\b"]
     and not re.match(r"\s*lord\b", r["lookahead_after_match"], re.IGNORECASE)),
    ("no_other_gods_regulates_worship_not_existence",
     lambda r: r"\bno other gods\b" in r["patterns_matched"]),
    ("formula_inside_hypothetical_protasis", lambda r: bool(CONDITIONAL_FRAME.match(r["sentence"]))),
)


