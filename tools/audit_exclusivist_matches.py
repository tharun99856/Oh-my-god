# ----------------------------------------------------------------- source dependence


def load_dependence():
    """Pair rules, oriented so that `left_work` is the source and `right_work` the derived witness."""
    config = json.loads(DEPENDENCE.read_text(encoding="utf-8"))
    derived_of = defaultdict(list)
    declared_anywhere = defaultdict(list)
    for rule in config["pair_rules"]:
        entry = {"with": rule["right_work"], "relationship": rule["relationship"],
                 "exclude_from_independent_analysis": rule["exclude_from_independent_analysis"],
                 "rationale": rule["rationale"]}
        declared_anywhere[rule["left_work"]].append(entry)
        declared_anywhere[rule["right_work"]].append(
            {"with": rule["left_work"], "relationship": rule["relationship"],
             "exclude_from_independent_analysis": rule["exclude_from_independent_analysis"],
             "rationale": rule["rationale"]})
        derived_of[rule["right_work"]].append({"source": rule["left_work"], "relationship": rule["relationship"],
                                               "exclude_from_independent_analysis":
                                                   rule["exclude_from_independent_analysis"],
                                               "rationale": rule["rationale"]})
    for entries in declared_anywhere.values():
        entries.sort(key=lambda item: (item["with"], item["relationship"]))
    for entries in derived_of.values():
        entries.sort(key=lambda item: (item["source"], item["relationship"]))
    return ({key: value for key, value in sorted(declared_anywhere.items())},
            {key: value for key, value in sorted(derived_of.items())})


